"""Run against a disposable GS_DATA_DIR (server on localhost:8787). Requires Playwright."""
from playwright.sync_api import sync_playwright
from pathlib import Path
import os
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True, executable_path=os.environ.get("GS_CHROMIUM"))
    page=browser.new_page(viewport={"width":1440,"height":1000})
    failures=[]
    page.on('pageerror',lambda e:failures.append(str(e)))
    page.on('dialog',lambda d:d.accept())
    def login(who):
        page.goto('http://localhost:8787')
        page.locator('#loginId').fill(who)
        page.locator('#loginPassword').fill('test1234')
        page.locator('#loginForm button').click()
        page.locator('#app').wait_for(state='visible')
        page.locator('[data-tab="list"]').wait_for()
    def logout():page.locator('#logout').click();page.locator('#login').wait_for(state='visible')
    login('a001')
    page.locator('[data-tab="new"]').click()
    page.locator('#startDate').fill('2027-03-04')
    page.locator('#endDate').fill('2027-03-04')
    page.locator('[data-history="destination"]').click()
    page.locator('[data-pick="0"]').click()
    assert page.locator('#destination').input_value()=='札幌市内'
    page.locator('#purpose').fill('映画')
    page.locator('[data-history="plan"]').click()
    page.locator('[data-pick="0"]').click()
    assert '買い物' in page.locator('#plan').input_value()
    page.locator('#destination').fill('あ'*21)
    page.locator('#requestForm button[type="submit"]').click()
    assert '20文字' in page.locator('#notice').inner_text()
    page.locator('#destination').fill('札幌駅周辺')
    page.screenshot(path='artifacts/input.png',full_page=True)
    page.locator('#requestForm button[type="submit"]').click()
    page.get_by_text('申請を保存しました',exact=True).wait_for()
    logout();login('b002')
    page.locator('[data-tab="approve"]').click()
    assert page.locator('[data-approve]').count()==0
    logout();login('b001')
    page.locator('[data-tab="approve"]').click()
    page.locator('[data-approve]').last.click()
    page.get_by_text('承認しました',exact=True).wait_for()
    logout();login('b002')
    page.locator('[data-tab="approve"]').click()
    page.locator('[data-approve]').last.click()
    page.get_by_text('承認しました',exact=True).wait_for()
    logout();login('d001')
    page.locator('[data-tab="duty"]').click()
    page.locator('#passSearch').fill('010')
    page.locator('#dutySearch button').click()
    page.locator('[data-duty]').wait_for()
    page.locator('[data-duty]').click()
    assert '確認チェック' in page.locator('#notice').inner_text()
    page.locator('[id^="drink-"]').check();page.locator('[id^="drive-"]').check()
    page.screenshot(path='artifacts/duty.png',full_page=True)
    page.locator('[data-duty]').click()
    page.get_by_text('交付日時を記録しました',exact=True).wait_for()
    page.locator('#passSearch').fill('010');page.locator('#dutySearch button').click()
    page.locator('[data-duty]').wait_for()
    page.locator('[id^="drink-"]').check();page.locator('[id^="drive-"]').check()
    page.locator('[data-duty]').click()
    page.get_by_text('返納日時を記録しました',exact=True).wait_for()
    page.locator('[data-tab="print"]').click()
    page.locator('#from').fill('2027-03-04');page.locator('#to').fill('2027-03-04');page.locator('#filter').click()
    assert '返納済み' in page.locator('#rows').inner_text()
    page.screenshot(path='artifacts/list.png',full_page=True)
    page.emulate_media(media='print')
    page.pdf(path='artifacts/print.pdf',prefer_css_page_size=True)
    page.emulate_media(media='screen')
    logout();login('admin')
    page.locator('[data-tab="users"]').click()
    page.locator('[data-user="a002"]').click()
    page.locator('#uPassword').fill('changed123')
    page.locator('#userForm button[type="submit"]').click()
    page.get_by_text('利用者情報を保存しました',exact=True).wait_for()
    logout()
    page.locator('#loginId').fill('a002');page.locator('#loginPassword').fill('changed123');page.locator('#loginForm button').click()
    page.locator('#app').wait_for(state='visible')
    assert failures==[],failures
    print('PASS: history, 20 chars, sequential approval, duty checks, return, print, admin password; no browser errors')
    browser.close()
